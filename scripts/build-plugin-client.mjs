import { readFile, readdir, writeFile } from 'node:fs/promises'

const client = new URL('../plugin-build/client/', import.meta.url)
const src = new URL('src/', client)
const index = new URL('index.js', client)
const header = '// Generated by scripts/build-client.mjs.\n(() => {\n'
const factoryHeader = `/* React and native conversation slots are supplied by DSH. */
window.__ModuleLoader__.load({
  id: 'dsh-marshal',
  factory(require) {
    const React = require('react');
    const { createSessionBridge, targetKey } = marshalNative();
    const { Setup, readSetup } = marshalSetup(React);
    const h = React.createElement;
`
const footer = '  },\n});\n\n})();\n'
const newline = Buffer.from('\n')

const names = (await readdir(src, { withFileTypes: true }))
  .filter(entry => entry.isFile() && entry.name.endsWith('.js'))
  .map(entry => entry.name)
  .sort((a, b) => a.localeCompare(b, 'en', { numeric: true }))
const [native, setup, ...shards] = await Promise.all([
  readFile(new URL('native.js', client)),
  readFile(new URL('setup.js', client)),
  ...names.map(name => readFile(new URL(name, src))),
])

// Shards share the factory scope and already contain their own line endings.
const bundle = Buffer.concat([
  Buffer.from(header), native, newline, setup, newline, Buffer.from(factoryHeader),
  ...shards, Buffer.from(footer),
])

if (process.argv.includes('--check')) {
  const current = await readFile(index).catch(error => {
    if (error.code !== 'ENOENT') throw error
    return null
  })
  if (!current || !bundle.equals(current)) {
    console.error('plugin-build/client/index.js is out of date. Run node scripts/build-plugin-client.mjs to regenerate it.')
    process.exitCode = 1
  }
} else {
  await writeFile(index, bundle)
}
