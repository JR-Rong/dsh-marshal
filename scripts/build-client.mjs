import { readFile, writeFile } from 'node:fs/promises'
const root = new URL('../', import.meta.url)
const sources = await Promise.all(['client/native.js', 'client/setup.js', 'client/panel.js'].map(path => readFile(new URL(path, root), 'utf8')))
await writeFile(new URL('client/index.js', root), '// Generated by scripts/build-client.mjs.\n' + '(() => {\n' + sources.join('\n') + '\n})();\n')
