import { chromium } from 'playwright-core'

const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--no-sandbox'] })
const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
const errors = []
page.on('pageerror', (error) => errors.push(String(error)))
await page.goto('http://127.0.0.1:5199/', { waitUntil: 'networkidle' })
const accent = () => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--accent').trim())
console.log('default', await page.evaluate(() => document.documentElement.dataset.theme), await accent())
await page.getByText('Codex 紫', { exact: true }).click()
await page.waitForFunction(() => document.documentElement.dataset.theme === 'purple')
console.log('purple', await accent())
await page.getByText('灰', { exact: true }).click()
await page.waitForFunction(() => document.documentElement.dataset.theme === 'gray')
console.log('gray', await accent())
await page.reload({ waitUntil: 'networkidle' })
console.log('reload', await page.evaluate(() => document.documentElement.dataset.theme), await accent())
await page.getByText('DeepSeek 蓝', { exact: true }).click()
await page.waitForFunction(() => document.documentElement.dataset.theme === 'blue')
console.log('blue', await accent())
await page.screenshot({ path: '/tmp/theme-blue.png', fullPage: false })
console.log('errors', errors)
await browser.close()
